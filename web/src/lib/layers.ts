export type CachePolicy = 'precache' | 'cache-first' | 'forecast'

export interface LayerDef {
  id: string
  title: string
  group: 'base' | 'overlay'
  /** Overlay tab; required for overlays. */
  category?: Category
  kind: LayerKind
  /** XYZ tile template, WMS endpoint, or bundled data path (relative to BASE_URL). */
  url: string
  wmsLayers?: string
  /** Extra WMS query parameters (styles, colour scales, ...). */
  params?: Record<string, string>
  /** Legend image URL shown in the layer panel when enabled. */
  legend?: string
  /** How a GeoJSON layer is drawn (default circle). */
  render?: 'circle' | 'fill' | 'dots'
  /** Client-side per-pixel alpha for density images (see lib/tileFilters.ts). */
  tileFilter?: TileFilter
  /** Hover lookup (GetFeatureInfo) configuration; density layers are sampled from decoded tiles instead. */
  info?: InfoSpec
  organisation: string
  license: string
  attribution: string
  cache: CachePolicy
  opacity?: number
  maxzoom?: number
  description?: string
}

