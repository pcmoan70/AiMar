/** Overlays of one tab, most important first (registry order for anything unranked). */
export function overlaysIn(category: Category): LayerDef[] {
  const order = CATEGORIES.find((c) => c.id === category)?.order ?? []
  const rank = (l: LayerDef) => (order.includes(l.id) ? order.indexOf(l.id) : order.length)
  return OVERLAY_LAYERS.filter((l) => l.category === category).sort((a, b) => rank(a) - rank(b))
}
export const layerById = (id: string) => LAYERS.find((l) => l.id === id)

export function wmsTileUrl(layer: LayerDef): string {
  const q = new URLSearchParams({
    service: 'WMS',
    request: 'GetMap',
    version: '1.3.0',
    layers: layer.wmsLayers ?? '',
    styles: '',
    crs: 'EPSG:3857',
    width: '256',
    height: '256',
    format: 'image/png',
    transparent: 'true',
    ...layer.params,
  })
  const sep = layer.url.includes('?') ? '&' : '?'
  return `${layer.url}${sep}${q.toString()}&bbox={bbox-epsg-3857}`
}

/** Legend images for a layer: an explicit `legend` when set, else one WMS GetLegendGraphic per sub-layer. */
export function legendUrls(l: LayerDef): string[] {
  if (l.legend) return [l.legend]
  if (l.kind !== 'wms' || !l.wmsLayers) return []
  const sep = l.url.includes('?') ? '&' : '?'
  return l.wmsLayers.split(',').map((name) => {
    const q = new URLSearchParams({ service: 'WMS', version: '1.3.0', request: 'GetLegendGraphic', format: 'image/png', layer: name.trim(), ...(l.params ?? {}) })
    return `${l.url}${sep}${q.toString()}`
  })
}
