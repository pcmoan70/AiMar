// Fixed colour table for operators. Rules:
//  1. Every operator with 16 or more active sites has a fixed colour. Operators
//     are grouped by brand — the first word of the name (MOWI, SALMAR, LERØY …)
//     — so related companies share a hue: the brand's largest member gets the
//     base colour and the others lighter or darker variants of it.
//  2. The table is only ever appended (by scripts/gen-operator-colours.mjs after
//     a data refresh), so a company keeps its colour across releases. Brands are
//     ranked by total sites; the first eight brands use the colour-blind-checked
//     palette, later brands the extended sequence below.
//  3. Every other operator is grey on the map ("other operators").
//  4. An unlisted operator selected in the dropdown borrows, while selected, a
//     free variant of its brand's hue if the brand is in the table, otherwise
//     the first sequence colour not used by a selected table operator.
//  5. A site with several licence holders takes the colour of the first table
//     entry it matches, else of the first selected operator it matches, else grey.
//  6. This site's own line in charts is navy and the "all farms" comparison is
//     dark grey; neither is an operator colour.

