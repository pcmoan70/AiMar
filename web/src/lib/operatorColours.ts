/** Brand = first word of the operator name. */
export const brandOf = (name: string) => name.trim().split(/\s+/)[0].toUpperCase()

// ---- colour helpers (mirrored in scripts/gen-operator-colours.mjs)
function hexToHsl(hex: string): [number, number, number] {
  const r = parseInt(hex.slice(1, 3), 16) / 255
  const g = parseInt(hex.slice(3, 5), 16) / 255
  const b = parseInt(hex.slice(5, 7), 16) / 255
  const max = Math.max(r, g, b)
  const min = Math.min(r, g, b)
  const l = (max + min) / 2
  if (max === min) return [0, 0, l]
  const d = max - min
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min)
  const h = max === r ? ((g - b) / d + (g < b ? 6 : 0)) / 6 : max === g ? ((b - r) / d + 2) / 6 : ((r - g) / d + 4) / 6
  return [h, s, l]
}
function hslToHex(h: number, s: number, l: number): string {
  const f = (n: number) => {
    const k = (n + h * 12) % 12
    const a = s * Math.min(l, 1 - l)
    return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1))
  }
  return '#' + [f(0), f(8), f(4)].map((v) => Math.round(v * 255).toString(16).padStart(2, '0')).join('')
}
const VARIANTS: [number, number][] = [[0, 0], [0.14, 0], [-0.14, 0], [0.24, -0.15], [-0.22, 0.1], [0.08, -0.3]]
/** k-th lightness/saturation variant of a base colour (k = 0 is the base itself). */
export function variant(base: string, k: number): string {
  const [h, s, l] = hexToHsl(base)
  const [dl, ds] = VARIANTS[k % VARIANTS.length]
  return hslToHex(h, Math.max(0.15, Math.min(1, s + ds)), Math.max(0.25, Math.min(0.8, l + dl)))
}
/** Hue in degrees, for tests and grouping checks. */
export const hueOf = (hex: string) => Math.round(hexToHsl(hex)[0] * 360)

const TABLE = new Map(OPERATOR_COLOURS.map((o) => [o.name, o.colour]))
const BRAND_BASE = new Map<string, string>()
for (const o of OPERATOR_COLOURS) if (!BRAND_BASE.has(o.brand)) BRAND_BASE.set(o.brand, o.colour)

/** Colour for every operator that matters right now: the table plus borrowed colours for selected unlisted operators. */
export function paletteFor(selected: string[]): Map<string, string> {
  const out = new Map(TABLE)
  const usedHues = new Set(selected.filter((s) => TABLE.has(s)).map((s) => TABLE.get(s)!))
  for (const op of selected) {
    if (out.has(op)) continue
    const base = BRAND_BASE.get(brandOf(op))
    let colour: string
    if (base) {
      const taken = new Set([...out.values()])
      let k = 0
      while (taken.has(variant(base, k)) && k < VARIANTS.length * 2) k++
      colour = variant(base, k)
    } else {
      colour = PALETTE.find((c) => !usedHues.has(c)) ?? OTHER_COLOUR
      usedHues.add(colour)
    }
    out.set(op, colour)
  }
  return out
}

/** Colour of a site given its comma-separated operator list (rule 5). */
export function siteColour(operators: string, selected: string[] = []): string {
  const pal = paletteFor(selected)
  const ops = operators.split(',').map((s) => s.trim())
  for (const o of OPERATOR_COLOURS) if (ops.includes(o.name)) return o.colour
  for (const s of selected) if (ops.includes(s)) return pal.get(s)!
  return OTHER_COLOUR
}
